// Download https://unicode.org/Public/17.0.0/emoji/emoji-test.txt, then run:
// node scripts/update-chat-emoji.mjs /path/to/emoji-test.txt
import { readFile, writeFile } from 'node:fs/promises'

const source = await readFile(process.argv[2], 'utf8')
const version = source.match(/^# Version: (.+)$/m)?.[1]
if (version !== '17.0') throw new Error('Expected the Unicode Emoji 17.0 catalog')
const groups = []
for (const line of source.split('\n')) {
  const group = line.match(/^# group: (.+)$/)
  if (group) groups.push({ name: group[1], emojis: [] })
  const entry = line.match(/^([0-9A-F ]+); (?:fully-qualified|component)\s+# \S+ E[\d.]+ (.+)$/)
  if (entry) groups.at(-1).emojis.push([
    String.fromCodePoint(...entry[1].trim().split(/\s+/).map(code => Number.parseInt(code, 16))),
    entry[2],
  ])
}
const emojis = groups.flatMap(group => group.emojis)
if (groups.length !== 10 || emojis.length !== 3953 || new Set(emojis.map(([emoji]) => emoji)).size !== emojis.length) {
  throw new Error('The catalog is incomplete or contains duplicate emoji')
}
const output = [
  '// Generated by scripts/update-chat-emoji.mjs. Do not edit by hand.',
  '// Unicode Emoji 17.0: https://unicode.org/Public/17.0.0/emoji/emoji-test.txt',
  '// Copyright © 2025 Unicode, Inc. License: public/licenses/unicode.txt',
  'export const CHAT_EMOJI_GROUPS: { name: string; emojis: [string, string][] }[] = [',
  ...groups.map(group => `  { name: ${JSON.stringify(group.name)}, emojis: [\n${group.emojis.map(entry => `    ${JSON.stringify(entry)},`).join('\n')}\n  ] },`),
  ']\n',
].join('\n')
await writeFile(new URL('../src/battle/emojiCatalog.ts', import.meta.url), output)
console.log(`Generated ${emojis.length} emoji in ${groups.length} categories`)
